export const UI: Record<Taal, Teksten> = { nl, en };
export const ui = (taal: Taal) => UI[taal];

/** "3 dagen online", alleen als het nieuws is: "90 dagen online" leest als oud, niet als vers. */
export function versheid(dagen: number | undefined, taal: Taal = "nl") {
  if (dagen === undefined || dagen > 30) return null;
  const t = UI[taal].jobs;
  if (dagen < 1) return { getal: t.nieuw, label: t.vandaag };
  return { getal: String(dagen), label: dagen === 1 ? t.dag : t.dagen };
}
